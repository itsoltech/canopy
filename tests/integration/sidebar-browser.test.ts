/** Opt-in browser acceptance on its own throwaway gateway/Postgres/scripted worker and web port.
 * OA_BROWSER_TESTS=1 bun test tests/integration/sidebar-browser.test.ts
 * Requires a web build, Chromium and playwright-core. No provider credentials or shared dev stack. */
import { afterAll, beforeAll, describe, expect, test } from "bun:test";
import { mkdirSync } from "node:fs";
import { resolve } from "node:path";
import { createRequire } from "node:module";
import type { BrowserContext, Page } from "playwright-core";
import { PermissionMode, Provider, ui } from "@open-agents/contracts";
import { tempDirs } from "@open-agents/testing";
import { eventually, startTestGateway, SERVICE_TOKEN, type TestGateway } from "./support/gateway.ts";

describe.skipIf(Bun.env["OA_BROWSER_TESTS"] !== "1")("sidebar browser acceptance", () => {
  const makeTemp = tempDirs();
  const shots = resolve(import.meta.dir, "../../artifacts/sidebar-filter-menu");
  const webPort = 5298;
  const base = `http://127.0.0.1:${webPort}`;
  let gw: TestGateway;
  let web: ReturnType<typeof Bun.spawn> | undefined;
  let desktop: BrowserContext;
  let mobile: BrowserContext;
  let parent: ui.Thread;
  let archived: ui.Thread;
  let other: ui.Thread;
  let alpha: ui.Project;
  let beta: ui.Project;
  const problems: string[] = [];
  const screenshot = (page: Page, name: string) => page.screenshot({ path: resolve(shots, `${name}.png`), animations: "disabled" });
  const visible = (page: Page, selector: string) => page.locator(selector).waitFor({ state: "visible" });

  beforeAll(async () => {
    mkdirSync(shots, { recursive: true });
    gw = await startTestGateway();
    alpha = (await gw.api.createProject({ name: "Alpha" })).project!;
    beta = (await gw.api.createProject({ name: "Beta" })).project!;
    const workspace = (await gw.api.createWorkspace({ projectId: alpha.id, workerId: gw.workerId, rootPath: "/repo/alpha" })).workspace!;
    const second = (await gw.api.createWorkspace({ projectId: beta.id, workerId: gw.workerId, rootPath: "/repo/beta" })).workspace!;
    await eventually(() => gw.api.getOverview({}), (o) => o.workers.every((w) => w.appliedVersion > 0n));
    const createThread = async (title: string, parentThreadId = "", otherProject = false) => {
      const t = (await gw.api.createThread({ title, parentThreadId, projectId: otherProject ? beta.id : alpha.id, workspaceId: otherProject ? second.id : workspace.id, provider: Provider.CODEX, permissionMode: PermissionMode.ASK, initialMessage: "Keep the timeline readable." })).thread!;
      await eventually(() => gw.api.getThread({ threadId: t.id }), (r) => r.thread?.status === "idle" && r.thread.lastSeq > 0n);
      return t;
    };
    parent = await createThread("Build sidebar navigation");
    await createThread("Active helper", parent.id);
    archived = await createThread("Previous helper", parent.id);
    await gw.worker.callTool({ threadId: parent.id, tool: "close_thread", args: { thread_id: archived.id } });
    other = await createThread("Beta release", "", true);
    const settings = (await gw.api.getSettings({})).user!;
    await gw.api.updateUserSettings({ expectedVersion: settings.version, appearance: { ...settings.appearance!, colorScheme: ui.ColorScheme.LIGHT, threadPanelCollapsed: false } });
    web = Bun.spawn(["bun", "build/index.js"], { cwd: resolve(import.meta.dir, "../../apps/web"),
      env: { ...Bun.env, HOST: "127.0.0.1", PORT: String(webPort), GATEWAY_URL: gw.grpcUrl, GATEWAY_SERVICE_TOKEN: SERVICE_TOKEN, ORIGIN: base }, stdout: "ignore", stderr: "inherit" });
    expect(await eventually(async () => fetch(`${base}/api/settings`).then((r) => r.ok).catch(() => false), Boolean, 20000)).toBe(true);
    const { chromium } = createRequire(import.meta.url)(Bun.env["OA_PLAYWRIGHT_MODULE"] ?? "playwright-core") as typeof import("playwright-core");
    const options = { executablePath: "/usr/bin/chromium", headless: true, args: ["--no-sandbox"] };
    desktop = await chromium.launchPersistentContext(makeTemp("oa-sidebar-desktop-"), { ...options, viewport: { width: 1440, height: 1000 }, colorScheme: "light" });
    mobile = await chromium.launchPersistentContext(makeTemp("oa-sidebar-touch-"), { ...options, viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, deviceScaleFactor: 1 });
    desktop.setDefaultTimeout(10000);
    mobile.setDefaultTimeout(10000);
    for (const context of [desktop, mobile]) context.on("page", (page) => page.on("pageerror", (e) => problems.push(e.message)));
  }, 60_000);

  afterAll(async () => {
    await desktop?.close(); await mobile?.close();
    web?.kill(); if (web) await web.exited;
    await gw?.close();
  }, 30_000);

  test("desktop: context, keyboard, projects, pin, Previous agents, archive, delete and Undo", async () => {
    const page = await desktop.newPage();
    await page.goto(`${base}/threads/${parent.id}`);
    const nav = page.getByRole("navigation", { name: "Threads", exact: true });
    const row = () => nav.locator(`a[href="/threads/${parent.id}"]`);
    await row().waitFor();
    await row().click({ button: "right" });
    const menu = page.getByRole("menu", { name: `Actions for ${parent.title}`, exact: true });
    await menu.waitFor();
    await screenshot(page, "desktop-light-menu");
    await page.keyboard.press("ArrowDown");
    expect(await page.locator(":focus").textContent()).toContain("New thread in");
    await page.keyboard.press("Escape");
    await menu.waitFor({ state: "hidden" });
    expect(await row().evaluate((node) => node.matches(":focus"))).toBe(true);
    await row().press("Shift+F10");
    await menu.getByRole("menuitem", { name: "Pin thread", exact: true }).click();
    await page.getByRole("heading", { name: "Pinned", exact: true }).waitFor();
    await page.getByRole("button", { name: "Filter projects", exact: true }).click();
    const filter = page.getByRole("dialog", { name: "Filter threads", exact: true });
    await filter.getByRole("searchbox", { name: "Search projects" }).fill("Alpha");
    await filter.getByRole("checkbox", { name: "Alpha", exact: true }).check();
    await screenshot(page, "desktop-light-filter");
    await nav.locator(`a[href="/threads/${other.id}"]`).waitFor({ state: "hidden" });
    await filter.getByRole("searchbox", { name: "Search projects" }).fill("");
    await filter.getByRole("checkbox", { name: "Beta", exact: true }).check();
    await nav.locator(`a[href="/threads/${other.id}"]`).waitFor();
    await filter.getByRole("button", { name: "Clear filters" }).click();
    await page.keyboard.press("Escape");
    const previous = nav.getByRole("button", { name: /Previous agents/ });
    expect(await previous.getAttribute("aria-expanded")).toBe("false");
    await previous.click();
    await nav.locator(`a[href="/threads/${archived.id}"]`).waitFor();
    await previous.click();
    const panel = page.locator('aside[aria-label="Thread details"]');
    if (await page.getByRole("button", { name: "Thread details", exact: true }).getAttribute("aria-pressed") !== "true") await page.getByRole("button", { name: "Thread details", exact: true }).click();
    await panel.getByRole("button", { name: /Previous agents/ }).click();
    await panel.locator(`a[href="/threads/${archived.id}"]`).waitFor();
    await row().press("Shift+F10");
    await menu.getByRole("menuitem", { name: "Archive thread", exact: true }).click();
    await page.getByRole("region", { name: "Archived thread", exact: true }).waitFor();
    await page.locator('form textarea, form [contenteditable="true"]').waitFor({ state: "hidden" });
    expect(await page.locator('form textarea, form [contenteditable="true"]').count()).toBe(0);
    await screenshot(page, "desktop-light-archived");
    await page.getByRole("button", { name: "Unarchive", exact: true }).click();
    await page.getByRole("region", { name: "Archived thread", exact: true }).waitFor({ state: "hidden" });
    await row().waitFor();
    await row().click({ button: "right" });
    await menu.getByRole("menuitem", { name: "Delete…", exact: true }).click();
    const confirm = page.getByRole("dialog", { name: "Delete thread?", exact: true });
    await confirm.waitFor();
    expect(await confirm.textContent()).toContain("2 side threads");
    await confirm.getByRole("button", { name: "Delete thread", exact: true }).click();
    await page.getByRole("button", { name: "Undo", exact: true }).click();
    await page.waitForURL(`${base}/threads/${parent.id}`);
    await row().waitFor();
    await page.goto(`${base}/threads/${archived.id}`);
    const state = page.getByRole("region", { name: "Archived thread", exact: true });
    await state.waitFor();
    expect(await state.textContent()).toContain(parent.title);
    await state.getByRole("link", { name: "Open parent thread", exact: true }).click();
    await page.waitForURL(`${base}/threads/${parent.id}`);
    await nav.locator(`a[href="/threads/${other.id}"]`).click({ button: "right" });
    await page.getByRole("menu", { name: `Actions for ${other.title}`, exact: true }).getByRole("menuitem", { name: "Rename…", exact: true }).click();
    const rename = page.getByRole("dialog", { name: "Rename thread", exact: true });
    await rename.getByRole("textbox", { name: "Thread title", exact: true }).fill("Beta navigation");
    await rename.getByRole("button", { name: "Save", exact: true }).click();
    await rename.waitFor({ state: "hidden" });
    expect((await gw.api.getThread({ threadId: other.id })).thread?.titleSource).toBe("user");
    await page.keyboard.press("Control+k");
    const palette = page.getByRole("dialog", { name: "Command palette", exact: true });
    await palette.getByRole("combobox").fill("Mark as unread");
    await page.keyboard.press("Enter");
    expect((await eventually(() => gw.api.getThread({ threadId: parent.id }), (r) => r.thread?.markedUnread === true)).thread?.markedUnread).toBe(true);
    await page.waitForTimeout(1200);
    expect((await gw.api.getThread({ threadId: parent.id })).thread?.markedUnread).toBe(true);
    await row().press("Shift+F10");
    await menu.getByRole("menuitem", { name: "Mark as read", exact: true }).click();
    const settings = (await gw.api.getSettings({})).user!;
    await gw.api.updateUserSettings({ expectedVersion: settings.version, appearance: { ...settings.appearance!, colorScheme: ui.ColorScheme.DARK } });
    await visible(page, "html.dark");
    await row().press("Shift+F10");
    await menu.waitFor();
    await screenshot(page, "desktop-dark-menu");
    await page.keyboard.press("Escape");
    expect(problems).toEqual([]);
    await page.close();
  }, 90_000);

  test("390px touch: tap navigates; long press opens the bottom sheet; Previous agents expands", async () => {
    await gw.api.setThreadArchived({ threadId: parent.id, archived: false });
    const page = await mobile.newPage();
    await page.goto(`${base}/threads/${parent.id}`);
    await page.getByRole("button", { name: "Open menu", exact: true }).click();
    const drawer = page.getByRole("dialog", { name: "Navigation", exact: true });
    const nav = drawer.getByRole("navigation", { name: "Threads", exact: true });
    const row = nav.locator(`a[href="/threads/${parent.id}"]`);
    await row.waitFor();
    const previous = drawer.getByRole("button", { name: /Previous agents/ });
    await previous.click();
    await drawer.locator(`a[href="/threads/${archived.id}"]`).waitFor();
    await previous.click();
    const bounds = await row.boundingBox();
    expect(bounds).not.toBeNull();
    const cdp = await mobile.newCDPSession(page);
    await cdp.send("Input.dispatchTouchEvent", { type: "touchStart", touchPoints: [{ x: bounds!.x + 50, y: bounds!.y + 40 }] });
    await page.waitForTimeout(600);
    await cdp.send("Input.dispatchTouchEvent", { type: "touchEnd", touchPoints: [] });
    const menu = page.getByRole("menu", { name: `Actions for ${parent.title}`, exact: true });
    await menu.waitFor();
    expect(await menu.getAttribute("data-sheet")).not.toBeNull();
    expect(page.url()).toBe(`${base}/threads/${parent.id}`);
    await screenshot(page, "mobile-dark-sheet");
    await page.keyboard.press("Escape");
    await drawer.locator(`a[href="/threads/${other.id}"]`).tap();
    await page.waitForURL(`${base}/threads/${other.id}`);
    await drawer.waitFor({ state: "hidden" });
    await page.goto(`${base}/threads/${archived.id}`);
    await page.getByRole("region", { name: "Archived thread", exact: true }).waitFor();
    await screenshot(page, "mobile-dark-archived");
    expect(problems).toEqual([]);
    await page.close();
  }, 60_000);
});
