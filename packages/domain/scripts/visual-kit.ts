import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { VISUAL_TOKEN_NAMES } from "../src/visuals/theme-tokens.ts";
import { visualTheme } from "../src/visuals/theme.ts";

// Bundles the visual kit (visual-kit/) into string constants the compiler inlines into every visual.
// `--check` fails when the committed output is stale. Bun is pinned (mise.toml), so the output is reproducible.

const root = join(import.meta.dir, "..");
const target = join(root, "src/visuals/gen/kit.ts");

async function bundle(entry: string): Promise<string> {
  const result = await Bun.build({ entrypoints: [join(root, entry)], minify: true, format: "iife", target: "browser" });

  if (!result.success) throw new AggregateError(result.logs, `Couldn't bundle ${entry}`);

  // ASCII only: non-ASCII appears solely in string and regex literals, where \u escapes mean the same. The
  // document's hash and bytes then never depend on how a host decodes it.
  return (await result.outputs[0]!.text())
    .trim()
    .replace(/[\u0080-\uffff]/g, (char) => `\\u${char.charCodeAt(0).toString(16).padStart(4, "0")}`);
}

function tokens(mode: "light" | "dark"): string {
  const theme = visualTheme("birch", mode);

  return VISUAL_TOKEN_NAMES.map((name) => `--${name}:${theme.colors[name]}`).join(";");
}

const script = await bundle("visual-kit/main.ts");
const style = await bundle("visual-kit/kit.css");
const defaults = `:root{color-scheme:light dark;${tokens("light")}}@media (prefers-color-scheme:dark){:root{${tokens("dark")}}}`;

for (const [name, text] of [
  ["script", script],
  ["style", style + defaults],
] as const)
  if (/<\/(script|style)|<!--/i.test(text)) throw new Error(`The kit ${name} contains a closing tag sequence.`);

const sha256 = createHash("sha256")
  .update(script)
  .update("\0")
  .update(style)
  .update("\0")
  .update(defaults)
  .digest("hex");

const output = `// Generated by packages/domain/scripts/visual-kit.ts (bun run gen). Do not edit.
export const KIT_SCRIPT = ${JSON.stringify(script)};
export const KIT_STYLE = ${JSON.stringify(style)};
export const KIT_DEFAULT_TOKENS = ${JSON.stringify(defaults)};
export const KIT_SHA256 = ${JSON.stringify(sha256)};
/** CSP source of the kit script; srcdoc frames inherit their host page's policy, which must allow exactly this. */
export const KIT_SCRIPT_CSP = ${JSON.stringify(`'sha256-${createHash("sha256").update(script).digest("base64")}'`)};
`;

if (process.argv.includes("--check")) {
  const current = await readFile(target, "utf8").catch(() => "");

  if (current !== output) {
    console.error("The visual kit is stale: run `bun run gen` in packages/domain.");
    process.exit(1);
  }
} else await writeFile(target, output);
